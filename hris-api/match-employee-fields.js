function parseArgs(argv) {
	const positionals = [];
	const flags = {
		json: false,
		csv: false,
		csvOut: path.join("reports", "employee-field-matches.csv"),
		clientReport: false,
		clientReportOut: path.join("reports", "employee-field-matches-client.svg"),
		strict: false,
		fuzzy: false,
		references: false,
		missingOnly: false,
		outJson: null,
	};

	for (let index = 0; index < argv.length; index += 1) {
		const arg = argv[index];
		if (arg === "--help" || arg === "-h") flags.help = true;
		else if (arg === "--json") flags.json = true;
		else if (arg === "--strict") flags.strict = true;
		else if (arg === "--fuzzy") flags.fuzzy = true;
		else if (arg === "--references") flags.references = true;
		else if (arg === "--missing-only") flags.missingOnly = true;
		else if (arg === "--csv") {
			flags.csv = true;
			const next = argv[index + 1];
			if (next && !next.startsWith("--")) {
				flags.csvOut = next;
				index += 1;
			}
		} else if (arg === "--client-report") {
			flags.clientReport = true;
			const next = argv[index + 1];
			if (next && !next.startsWith("--")) {
				flags.clientReportOut = next;
				index += 1;
			}
		} else if (arg === "--out-json") {
			const next = argv[index + 1];
			if (!next || next.startsWith("--")) throw new Error("--out-json requires a file path");
			flags.outJson = next;
			index += 1;
		} else if (arg.startsWith("--")) {
			throw new Error(`Unknown flag: ${arg}`);
		} else {
			positionals.push(arg);
		}
	}

	return {
		workbookPath: positionals[0],
		prismaPath: positionals[1],
		configPath: positionals[2],
		flags,
	};
}

function resolveExisting(input, label) {
	if (!input) throw new Error(`${label} is required`);
	const resolved = path.isAbsolute(input) ? input : path.resolve(process.cwd(), input);
	if (!fs.existsSync(resolved)) throw new Error(`${label} not found: ${resolved}`);
	return resolved;
}

function normalize(value) {
	return String(value || "")
		.toLowerCase()
		.replace(/[\u00a0\u3000]/g, " ")
		.replace(/([a-z0-9])([A-Z])/g, "$1 $2")
		.replace(/[^a-z0-9]+/g, " ")
		.trim()
		.replace(/\s+/g, " ");
}

function unique(values) {
	return Array.from(new Set(values.filter(Boolean)));
}

function readWorkbookColumns(workbookPath) {
	const workbook = XLSX.readFile(workbookPath, { cellDates: true });
	const columns = [];

	for (const sheetName of workbook.SheetNames) {
		const rows = XLSX.utils.sheet_to_json(workbook.Sheets[sheetName], {
			header: 1,
			blankrows: false,
			defval: null,
			raw: false,
		});
		if (!rows.length) continue;

		const headerRowIndex = rows.findIndex((row) => row.some((cell) => String(cell || "").trim()));
		if (headerRowIndex < 0) continue;

		const headerRow = rows[headerRowIndex];
		const dataRows = rows.slice(headerRowIndex + 1);

		headerRow.forEach((rawHeader, index) => {
			const header = String(rawHeader || "").trim();
			const normalized = normalize(header);
			if (!normalized) return;
			const values = dataRows.map((row) => String(row[index] || "").trim()).filter(Boolean);
			columns.push({
				header,
				normalized,
				sheet: sheetName,
				columnLetter: XLSX.utils.encode_col(index),
				sourceRef: `${sheetName}!${XLSX.utils.encode_col(index)}${headerRowIndex + 1}`,
				nonEmpty: values.length,
				totalRows: dataRows.length,
				completeness: dataRows.length ? values.length / dataRows.length : 0,
			});
		});
	}

	return columns;
}

function parsePrismaFields(prismaText) {
	const fields = [];
	const blockPattern = /\b(model|type)\s+(\w+)\s*\{([\s\S]*?)\n\}/g;
	let blockMatch;
	while ((blockMatch = blockPattern.exec(prismaText))) {
		const model = blockMatch[2];
		const block = blockMatch[3];
		for (const line of block.split(/\r?\n/)) {
			const trimmed = line.trim();
			if (!trimmed || trimmed.startsWith("//") || trimmed.startsWith("@@")) continue;
			const fieldMatch = /^([A-Za-z_]\w*)\s+([A-Za-z_]\w*)(\[\]|\?)?/.exec(trimmed);
			if (!fieldMatch) continue;
			fields.push(`${model}.${fieldMatch[1]}`);
		}
	}
	return new Set(fields);
}

function loadAliasConfig(configPath) {
	if (!configPath) return {};
	const resolved = resolveExisting(configPath, "Alias config");
	const parsed = JSON.parse(fs.readFileSync(resolved, "utf8"));
	return Object.fromEntries(
		Object.entries(parsed).map(([key, value]) => [normalize(key), Array.isArray(value) ? value : [value]]),
	);
}

function levenshtein(a, b) {
	const matrix = Array.from({ length: a.length + 1 }, (_, row) => [row]);
	for (let column = 1; column <= b.length; column += 1) matrix[0][column] = column;
	for (let row = 1; row <= a.length; row += 1) {
		for (let column = 1; column <= b.length; column += 1) {
			const cost = a[row - 1] === b[column - 1] ? 0 : 1;
			matrix[row][column] = Math.min(
				matrix[row - 1][column] + 1,
				matrix[row][column - 1] + 1,
				matrix[row - 1][column - 1] + cost,
			);
		}
	}
	return matrix[a.length][b.length];
}

function similarity(a, b) {
	const left = normalize(a).replace(/\s/g, "");
	const right = normalize(b).replace(/\s/g, "");
	if (!left || !right) return 0;
	if (left === right) return 1;
	if (left.includes(right) || right.includes(left)) return Math.min(left.length, right.length) / Math.max(left.length, right.length);
	return 1 - levenshtein(left, right) / Math.max(left.length, right.length);
}

function matchesAlias(alias, column) {
	const normalizedAlias = normalize(alias);
	const exactOnly = normalizedAlias.length <= 4 || ["pin", "mid"].includes(normalizedAlias);
	return exactOnly
		? column.normalized === normalizedAlias
		: column.normalized === normalizedAlias || column.normalized.includes(normalizedAlias);
}

function findBestColumns(field, columns, aliasConfig, flags) {
	const configuredAliases = Object.entries(aliasConfig)
		.filter(([, targets]) => targets.some((target) => normalize(target) === normalize(field.field)))
		.map(([alias]) => alias);
	const aliases = unique([...field.aliases, ...configuredAliases]);
	let matches = columns.filter((column) => aliases.some((alias) => matchesAlias(alias, column)));

	if (!matches.length && flags.fuzzy && !flags.strict) {
		const scored = columns
			.map((column) => ({
				column,
				score: Math.max(...aliases.map((alias) => similarity(alias, column.normalized))),
			}))
			.filter((item) => item.score >= 0.8)
			.sort((a, b) => b.score - a.score);
		matches = scored.map((item) => item.column);
	}

	return matches.sort((a, b) => b.completeness - a.completeness);
}

function sourceLabel(columns, limit = 3) {
	if (!columns.length) return "-";
	return columns
		.slice(0, limit)
		.map((column) => `${column.header} (${column.sourceRef}, ${Math.round(column.completeness * 100)}%)`)
		.join("; ");
}

function compareFields(columns, aliasConfig, flags, parsedPrismaFields) {
	const results = IMPORTANT_FIELDS.map((field) => {
		const matchedColumns = findBestColumns(field, columns, aliasConfig, flags);
		const bestCompleteness = matchedColumns[0]?.completeness || 0;
		const status = matchedColumns.length ? field.statusWhenFound : STATUSES.MISSING;
		const schemaPresent =
			parsedPrismaFields.has(field.field) ||
			field.field.includes(".personalInfo.") ||
			field.field.includes(".contactInfo.") ||
			field.field.startsWith("ContactAddress.") ||
			field.field.startsWith("Document(") ||
			field.field.startsWith("Person.children") ||
			field.field.includes(".employmentHistory.");

		return {
			hrisField: field.label,
			prismaField: field.field,
			group: field.group,
			xlsColumn: matchedColumns[0]?.header || null,
			xlsSource: sourceLabel(matchedColumns),
			status,
			matchType: matchedColumns.length ? "alias" : "none",
			confidence: matchedColumns.length ? 0.95 : 0,
			completeness: bestCompleteness,
			schemaPresent,
			action: field.action,
			matchedColumns,
		};
	});

	const usedSourceRefs = new Set(results.flatMap((result) => result.matchedColumns.map((column) => column.sourceRef)));
	const seenUnknownHeaders = new Set();
	const unknownColumns = columns
		.filter((column) => !usedSourceRefs.has(column.sourceRef))
		.filter((column) => {
			const key = column.normalized;
			if (seenUnknownHeaders.has(key)) return false;
			seenUnknownHeaders.add(key);
			return true;
		})
		.map((column) => ({
			hrisField: "Unknown workbook column",
			prismaField: null,
			group: "Unknown",
			xlsColumn: column.header,
			xlsSource: `${column.sourceRef} (${Math.round(column.completeness * 100)}%)`,
			status: STATUSES.UNKNOWN,
			matchType: "none",
			confidence: 0,
			completeness: column.completeness,
			schemaPresent: false,
			action: "Review with client; no important HRIS target was identified.",
			matchedColumns: [column],
		}));

	return { results, unknownColumns };
}

function summarize(results, unknownColumns) {
	return {
		matches: results.filter((result) => result.status === STATUSES.MATCH).length,
		references: results.filter((result) => result.status === STATUSES.REFERENCE).length,
		missing: results.filter((result) => result.status === STATUSES.MISSING).length,
		derived: results.filter((result) => result.status === STATUSES.DERIVED).length,
		unknownColumns: unknownColumns.length,
	};
}

function pad(value, width) {
	const text = String(value == null || value === "" ? "-" : value);
	return text.padEnd(width);
}

function renderTable(results, unknownColumns, summary, context) {
	const visible = results;
	const fieldWidth = Math.max(22, ...visible.map((row) => row.hrisField.length + 2));
	const prismaWidth = Math.max(28, ...visible.map((row) => row.prismaField.length + 2));
	const xlsWidth = Math.max(22, ...visible.map((row) => String(row.xlsColumn || "-").length + 2));
	const line = "-".repeat(Math.max(112, fieldWidth + prismaWidth + xlsWidth + 34));
	const rows = [];

	rows.push(line);
	rows.push("EMPLOYEE FIELD MATCHING RESULT");
	rows.push(line);
	rows.push(`Workbook: ${path.basename(context.workbookPath)}`);
	rows.push(`Schema  : ${path.relative(process.cwd(), context.prismaPath) || context.prismaPath}`);
	rows.push("");
	rows.push(`${pad("FIELD", fieldWidth)} | ${pad("PRISMA TARGET", prismaWidth)} | ${pad("XLS INPUT COLUMN", xlsWidth)} | STATUS`);
	rows.push(line);
	for (const row of visible) {
		rows.push(`${pad(row.hrisField, fieldWidth)} | ${pad(row.prismaField, prismaWidth)} | ${pad(row.xlsColumn || "-", xlsWidth)} | ${row.status}`);
	}

	if (unknownColumns.length) {
		rows.push("");
		rows.push("UNKNOWN XLS COLUMNS");
		rows.push(line);
		for (const row of unknownColumns) {
			rows.push(`${pad("-", fieldWidth)} | ${pad("-", prismaWidth)} | ${pad(row.xlsColumn, xlsWidth)} | ${row.status}`);
		}
	}

	rows.push("");
	rows.push(line);
	rows.push("SUMMARY");
	rows.push(line);
	rows.push(`Matches         : ${summary.matches}`);
	rows.push(`References      : ${summary.references}`);
	rows.push(`Missing         : ${summary.missing}`);
	rows.push(`Derived         : ${summary.derived}`);
	rows.push(`Unknown Columns : ${summary.unknownColumns}`);
	rows.push(line);
	return rows.join("\n");
}

function csvEscape(value) {
	const text = String(value == null ? "" : value);
	return /[",\n]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text;
}

function flattenRows(results, unknownColumns) {
	return [...results, ...unknownColumns].map((row) => ({
		hrisField: row.hrisField,
		prismaField: row.prismaField,
		xlsColumn: row.xlsColumn,
		xlsSource: row.xlsSource,
		status: row.status,
		group: row.group,
		matchType: row.matchType,
		confidence: row.confidence,
		completeness: row.completeness,
		schemaPresent: row.schemaPresent,
		action: row.action,
	}));
}

function writeCsv(rows, csvPath) {
	const resolved = path.isAbsolute(csvPath) ? csvPath : path.resolve(process.cwd(), csvPath);
	fs.mkdirSync(path.dirname(resolved), { recursive: true });
	const headers = [
		"group",
		"hrisField",
		"prismaField",
		"xlsColumn",
		"xlsSource",
		"status",
		"completeness",
		"action",
	];
	const lines = [headers.join(","), ...rows.map((row) => headers.map((header) => csvEscape(row[header])).join(","))];
	fs.writeFileSync(resolved, `${lines.join("\n")}\n`, "utf8");
	return resolved;
}

function xmlEscape(value) {
	return String(value == null ? "" : value)
		.replace(/&/g, "&amp;")
		.replace(/</g, "&lt;")
		.replace(/>/g, "&gt;")
		.replace(/"/g, "&quot;");
}

function statusColor(status) {
	if (status === STATUSES.MATCH) return "#1f9d55";
	if (status === STATUSES.REFERENCE) return "#1f6feb";
	if (status === STATUSES.DERIVED) return "#b7791f";
	if (status === STATUSES.MISSING) return "#d64545";
	return "#6b7280";
}

function clientStatusTone(status) {
	if (status === STATUSES.MATCH) {
		return { text: "#177245", fill: "#eef8f1", row: "#fbfdfb" };
	}
	if (status === STATUSES.REFERENCE) {
		return { text: "#1d5f99", fill: "#eff6ff", row: "#fbfdff" };
	}
	if (status === STATUSES.DERIVED) {
		return { text: "#9a5b00", fill: "#fff6df", row: "#fffdf7" };
	}
	if (status === STATUSES.MISSING) {
		return { text: "#b42318", fill: "#fff1f1", row: "#fffafa" };
	}
	return { text: "#5f5f63", fill: "#f2f2f2", row: "#fcfcfc" };
}

function wrapText(value, maxChars, maxLines = 2) {
	const words = String(value == null || value === "" ? "-" : value).split(/\s+/);
	const lines = [];
	let current = "";
	for (const word of words) {
		const next = current ? `${current} ${word}` : word;
		if (next.length > maxChars && current) {
			lines.push(current);
			current = word;
		} else {
			current = next;
		}
	}
	if (current) lines.push(current);
	return lines.slice(0, maxLines);
}

function svgTextBlock({
	x,
	y,
	value,
	maxChars,
	maxLines = 2,
	fontSize = 13,
	fill = "#263244",
	weight = "400",
	fontFamily = "Aptos, Calibri, sans-serif",
}) {
	const lines = wrapText(value, maxChars, maxLines);
	return lines
		.map((line, index) => {
			const dy = index * (fontSize + 3);
			return `<text x="${x}" y="${y + dy}" font-family="${fontFamily}" font-size="${fontSize}" font-weight="${weight}" fill="${fill}">${xmlEscape(line)}</text>`;
		})
		.join("\n");
}

function clientActionText(row) {
	return String(row.action || "")
		.replace(/linked Person legal-name record/g, "employee legal-name profile")
		.replace(/linked Person address record/g, "employee address profile")
		.replace(/Person/g, "employee profile")
		.replace(/Derive ACTIVE\/INACTIVE\/RESIGNED/g, "Confirm active, inactive, or resigned status")
		.replace(/REGULAR, PROBATIONARY, CONTRACTUAL, PART_TIME, CONSULTANT, or INTERN/g, "regular, probationary, contractual, part-time, consultant, or intern");
}

function compactClientActionText(row) {
	const field = row.hrisField;
	if (row.status === STATUSES.MATCH) {
		if (field === "Dependents") return "Keep for later";
		if (field === "Previous employment period" && row.completeness < 0.05) return "Keep for later";
		return "Use from TIN Library";
	}
	if (row.status === STATUSES.REFERENCE) {
		if (field === "Reports-to employee") return "Need supervisor employee no.";
		return "Review mapping list";
	}
	if (row.status === STATUSES.DERIVED) {
		if (field === "Employment start date") return "Use hire date if approved";
		if (field === "Employment status") return "Confirm employee status";
		if (field === "Resignation/termination date") return "Review former employees";
		return "Please confirm";
	}
	if (row.status === STATUSES.MISSING) {
		const askByField = {
			Gender: "Provide or skip for phase 1",
			Nationality: "Provide or skip for phase 1",
			Email: "Needed for logins",
			Phone: "Useful but not urgent",
			"Level/grade/rank": "Need level mapping",
			"Reports-to employee": "Need supervisor employee no.",
			"Employment start date": "Use hire date if approved",
			"Employment type": "Need employee type",
			"Workforce source": "Need direct/agency/expat",
			"Work location": "Use ONSITE if approved",
			"Default schedule/shift": "Need schedule or shift",
			"Basic salary": "Need current rate",
			"Pay frequency": "Use SEMI_MONTHLY",
			Currency: "Use PHP",
			"Biometric/RFID ID": "Need for timekeeping match",
			"SSS number": "Need SSS or status",
			"PhilHealth number": "Need PhilHealth or status",
			"Pag-IBIG MID": "Need Pag-IBIG or status",
		};
		return askByField[field] || "Need from Bandai Namco";
	}
	return "Review with HR";
}

function compactStatusLabel(row) {
	if (row.status === STATUSES.MATCH) return "Ready";
	if (row.status === STATUSES.REFERENCE) return "Map first";
	if (row.status === STATUSES.DERIVED) return "Confirm";
	if (row.status === STATUSES.MISSING) {
		if (["Pay frequency", "Currency", "Work location", "Employment start date"].includes(row.hrisField)) {
			return "Use default";
		}
		if (
			[
				"Basic salary",
				"SSS number",
				"PhilHealth number",
				"Pag-IBIG MID",
				"Reports-to employee",
				"Level/grade/rank",
				"Employment type",
				"Workforce source",
				"Default schedule/shift",
			].includes(row.hrisField)
		) {
			return "Required";
		}
		return "Ask";
	}
	return "Review";
}

function writeClientSvg(results, unknownColumns, summary, reportPath, context) {
	const resolved = path.isAbsolute(reportPath) ? reportPath : path.resolve(process.cwd(), reportPath);
	fs.mkdirSync(path.dirname(resolved), { recursive: true });
	const rows = results.map((row) => ({
		...row,
		compactStatus: compactStatusLabel(row),
		compactAction: compactClientActionText(row),
	}));
	const width = 1600;
	const height = 1000;
	const margin = 34;
	const contentX = margin;
	const contentWidth = width - margin * 2;
	const tableX = contentX;
	const tableY = 82;
	const rowHeight = 20;
	const headerHeight = 25;
	const parts = [];
	const font = "Aptos, Calibri, sans-serif";
	const colors = {
		bg: "#ffffff",
		text: "#171717",
		muted: "#5f6368",
		line: "#d8dadd",
		header: "#202124",
		headerText: "#ffffff",
		soft: "#f6f7f8",
	};
	const cols = {
		group: { x: tableX, w: 166 },
		field: { x: tableX + 166, w: 252 },
		source: { x: tableX + 418, w: 245 },
		status: { x: tableX + 663, w: 92 },
		next: { x: tableX + 755, w: 250 },
		owner: { x: tableX + 1005, w: 170 },
		note: { x: tableX + 1175, w: contentWidth - 1175 },
	};
	const tableHeight = headerHeight + rows.length * rowHeight;

	parts.push(`<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}">`);
	parts.push(`<rect width="${width}" height="${height}" fill="${colors.bg}"/>`);
	parts.push(`<text x="${contentX}" y="44" font-family="${font}" font-size="24" font-weight="700" fill="${colors.text}">Bandai Namco Employee Data Checklist</text>`);

	parts.push(`<rect x="${tableX}" y="${tableY}" width="${contentWidth}" height="${headerHeight}" fill="${colors.header}"/>`);
	const headerY = tableY + 17;
	[
		["AREA", cols.group],
		["EMPLOYEE DATA", cols.field],
		["TIN LIBRARY COLUMN", cols.source],
		["STATUS", cols.status],
		["WHAT TO DO", cols.next],
		["OWNER", cols.owner],
		["NOTE", cols.note],
	].forEach(([label, col]) => {
		parts.push(`<text x="${col.x + 8}" y="${headerY}" font-family="${font}" font-size="9.5" font-weight="700" fill="${colors.headerText}">${label}</text>`);
	});

	function ownerFor(row) {
		if (["Basic salary", "SSS number", "PhilHealth number", "Pag-IBIG MID"].includes(row.hrisField)) return "Payroll / HR";
		if (["Reports-to employee", "Level/grade/rank", "Employment type", "Workforce source"].includes(row.hrisField)) return "HR";
		if (["Default schedule/shift", "Biometric/RFID ID"].includes(row.hrisField)) return "HR / Timekeeping";
		if (["Department", "Position"].includes(row.hrisField)) return "UZARO + HR";
		if (["Pay frequency", "Currency", "Work location", "Employment start date", "Employment status"].includes(row.hrisField)) return "HR signoff";
		if (row.status === STATUSES.MATCH) return "UZARO";
		return "Bandai Namco";
	}

	function noteFor(row) {
		if (row.status === STATUSES.MATCH) return "Can be used from the file";
		if (row.status === STATUSES.REFERENCE) return row.hrisField === "Reports-to employee" ? "Needed for approvals and org chart" : "Needs agreed HRIS naming";
		if (row.status === STATUSES.DERIVED) return "Please review before import";
		if (row.compactStatus === "Use default") return "Can save manual encoding";
		if (row.compactStatus === "Required") return "Needed before rollout";
		if (row.status === STATUSES.UNKNOWN) return "Decide if useful";
		return "Not in the file";
	}

	rows.forEach((row, index) => {
		const y = tableY + headerHeight + index * rowHeight;
		const fill = index % 2 === 0 ? "#ffffff" : "#fafafa";
		parts.push(`<rect x="${tableX}" y="${y}" width="${contentWidth}" height="${rowHeight}" fill="${fill}" stroke="${colors.line}" stroke-width="0.6"/>`);
		[cols.group, cols.field, cols.source, cols.status, cols.next, cols.owner].forEach((col) => {
			parts.push(`<line x1="${col.x}" y1="${y}" x2="${col.x}" y2="${y + rowHeight}" stroke="${colors.line}" stroke-width="0.6"/>`);
		});
		const textY = y + 14;
		const statusFill = row.compactStatus === "Required" ? "#8a1f1f" : row.compactStatus === "Use default" ? "#6a4a00" : row.compactStatus === "Map first" ? "#333333" : "#2f5d3a";
		parts.push(svgTextBlock({ x: cols.group.x + 8, y: textY, value: row.group, maxChars: 23, maxLines: 1, fontSize: 9.3, fill: colors.muted }));
		parts.push(svgTextBlock({ x: cols.field.x + 8, y: textY, value: row.hrisField, maxChars: 34, maxLines: 1, fontSize: 9.8, fill: colors.text, weight: "700" }));
		parts.push(svgTextBlock({ x: cols.source.x + 8, y: textY, value: row.xlsColumn || "Not found", maxChars: 32, maxLines: 1, fontSize: 9.5, fill: row.xlsColumn ? colors.text : colors.muted }));
		parts.push(`<text x="${cols.status.x + 8}" y="${textY}" font-family="${font}" font-size="8.8" font-weight="700" fill="${statusFill}">${xmlEscape(row.compactStatus)}</text>`);
		parts.push(svgTextBlock({ x: cols.next.x + 8, y: textY, value: row.compactAction, maxChars: 34, maxLines: 1, fontSize: 9.5, fill: colors.text }));
		parts.push(svgTextBlock({ x: cols.owner.x + 8, y: textY, value: ownerFor(row), maxChars: 23, maxLines: 1, fontSize: 9.5, fill: colors.text }));
		parts.push(svgTextBlock({ x: cols.note.x + 8, y: textY, value: noteFor(row), maxChars: 48, maxLines: 1, fontSize: 9.3, fill: colors.muted }));
	});
	parts.push(`<rect x="${tableX}" y="${tableY}" width="${contentWidth}" height="${tableHeight}" fill="none" stroke="${colors.header}" stroke-width="1"/>`);

	const footerY = tableY + tableHeight + 22;
	const blockerText = "Before rollout, Bandai Namco should provide: basic salary, SSS, PhilHealth, Pag-IBIG, supervisor employee no., level mapping, employment type, workforce source, schedule/shift, and device ID if timekeeping matching is included.";
	parts.push(`<text x="${contentX}" y="${footerY}" font-family="${font}" font-size="12" font-weight="700" fill="${colors.text}">Needed before rollout</text>`);
	parts.push(svgTextBlock({ x: contentX, y: footerY + 20, value: blockerText, maxChars: 172, maxLines: 2, fontSize: 10.5, fill: colors.muted }));
	if (unknownColumns.length) {
		const unknownText = `Workbook columns needing review: ${unknownColumns.map((row) => row.xlsColumn).join(", ")}`;
		parts.push(svgTextBlock({ x: contentX, y: footerY + 50, value: unknownText, maxChars: 172, maxLines: 1, fontSize: 10, fill: colors.muted }));
	}
	parts.push(`</svg>`);

	fs.writeFileSync(resolved, parts.join("\n"), "utf8");
	return resolved;
}

function main() {
	const args = parseArgs(process.argv.slice(2));
	if (args.flags.help) {
		usage();
		return;
	}

	const workbookPath = resolveExisting(args.workbookPath, "Workbook");
	const prismaPath = resolveExisting(args.prismaPath, "Prisma schema");
	const aliasConfig = loadAliasConfig(args.configPath);
	const columns = readWorkbookColumns(workbookPath);
	const parsedPrismaFields = parsePrismaFields(fs.readFileSync(prismaPath, "utf8"));
	if (!columns.length) throw new Error("No workbook columns were detected");

	let { results, unknownColumns } = compareFields(columns, aliasConfig, args.flags, parsedPrismaFields);
	if (args.flags.missingOnly) {
		results = results.filter((result) => result.status === STATUSES.MISSING);
		unknownColumns = [];
	}
	const summary = summarize(results, unknownColumns);
	const rows = flattenRows(results, unknownColumns);

	if (args.flags.outJson) {
		const resolved = path.isAbsolute(args.flags.outJson) ? args.flags.outJson : path.resolve(process.cwd(), args.flags.outJson);
		fs.mkdirSync(path.dirname(resolved), { recursive: true });
		fs.writeFileSync(resolved, `${JSON.stringify(rows, null, 2)}\n`, "utf8");
	}

	if (args.flags.csv) {
		const csvOut = writeCsv(rows, args.flags.csvOut);
		if (!args.flags.json) console.log(`CSV report: ${csvOut}`);
	}

	if (args.flags.clientReport) {
		const reportOut = writeClientSvg(results, unknownColumns, summary, args.flags.clientReportOut, {
			workbookPath,
			prismaPath,
		});
		if (!args.flags.json) console.log(`Client SVG report: ${reportOut}`);
	}

	if (args.flags.json) {
		console.log(JSON.stringify(rows, null, 2));
		return;
	}

	console.log(renderTable(results, unknownColumns, summary, { workbookPath, prismaPath }));
}

try {
	main();
} catch (error) {
	console.error(error instanceof Error ? error.message : error);
	process.exitCode = 1;
}
